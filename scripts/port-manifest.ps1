# port-manifest.ps1 - XFP0 port provenance and coverage gate.
#
# Verifies docs/xemu-port-manifest.md against the reference tree and the source:
#   1. every hw/xbox/** reference file has exactly one row in the generated
#      per-file appendix (no silent omissions, no stale rows);
#   2. every `ported`/`verified` row names a target file that exists;
#   3. every `Ported from`/`Derived from` header in src/** names a reference
#      path the ledger knows;
#   4. every `ported`/`verified` reference file is named in
#      THIRD_PARTY_NOTICES.md (basename match);
#   5. prints the status coverage.
# Exit 0 only when every check is green.
#
# -UpdateFileList regenerates the appendix from References2/xemu-0.8.139.
#
# Usage (from the repo root):
#   pwsh -File scripts/port-manifest.ps1 -Check
#   pwsh -File scripts/port-manifest.ps1 -UpdateFileList

param(
    [switch]$Check,
    [switch]$UpdateFileList
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$refDir = Join-Path $root "References2\xemu-0.8.139\hw\xbox"
$manifestPath = Join-Path $root "docs\xemu-port-manifest.md"
$noticesPath = Join-Path $root "THIRD_PARTY_NOTICES.md"
$beginMarker = "<!-- HW-XBOX-FILES:BEGIN (generated by scripts/port-manifest.ps1 -UpdateFileList) -->"
$endMarker = "<!-- HW-XBOX-FILES:END -->"

if (-not (Test-Path $refDir)) {
    Write-Error "reference tree not found: $refDir (References2 is required; see AGENTS.md)"
    exit 2
}

if (-not $Check -and -not $UpdateFileList) {
    $Check = $true
}

function New-Entry([string]$target, [string]$status, [string]$class) {
    return [pscustomobject]@{ Target = $target; Status = $status; Class = $class }
}

# The per-file status rules. First match wins; the order encodes the exceptions.
function Get-Entry([string]$rel) {
    if ($rel -match '(^|/)meson\.build$' -or $rel -match 'trace-events$') {
        return New-Entry "-" "n/a" "build/trace metadata"
    }

    if ($rel -like "chihiro*") {
        return New-Entry "-" "out-of-scope" "Sega Chihiro arcade hardware"
    }

    if ($rel -like "nv2a/pgraph/vk/*") {
        return New-Entry "-" "out-of-scope" "host renderer choice"
    }

    if ($rel -like "nv2a/pgraph/null/*") {
        return New-Entry "-" "n/a" "null renderer"
    }

    if ($rel -like "nv2a/pgraph/gl/*") {
        return New-Entry "src/XGrid.GpuGl" "not-started" "GL renderer port (XFP5)"
    }

    if ($rel -eq "nv2a/pgraph/glsl/psh.c") {
        return New-Entry "src/XGrid.Nv2a/PshCombiner.cs" "verified" "register/method table + live GL compile + corpus"
    }

    if ($rel -eq "nv2a/pgraph/glsl/psh.h") {
        return New-Entry "src/XGrid.GpuGl/PshGlslGenerator.cs" "in-progress" "shader generator (XFP3)"
    }

    if ($rel -eq "nv2a/pgraph/glsl/vsh-prog.c") {
        return New-Entry "src/XGrid.Nv2a/VshProgram.cs" "verified" "VshProgramPlanTests + corpus"
    }

    if ($rel -eq "nv2a/pgraph/glsl/vsh-prog.h") {
        return New-Entry "src/XGrid.Nv2a/VshProgram.cs" "ported" "register decode"
    }

    if ($rel -eq "nv2a/pgraph/glsl/vsh-ff.c") {
        return New-Entry "src/XGrid.Nv2a/FixedFunctionVertex.cs" "verified" "xgu *_ffp corpus rows"
    }

    if ($rel -eq "nv2a/pgraph/glsl/vsh-ff.h") {
        return New-Entry "src/XGrid.Nv2a/FixedFunctionVertexState.cs" "ported" "decode"
    }

    if ($rel -eq "nv2a/pgraph/glsl/vsh.c" -or $rel -eq "nv2a/pgraph/glsl/vsh.h") {
        return New-Entry "src/XGrid.Nv2a/FixedFunctionVertexState.cs" "ported" "decode"
    }

    if ($rel -like "nv2a/pgraph/glsl/*") {
        return New-Entry "src/XGrid.GpuGl" "in-progress" "shader generator (XFP3)"
    }

    if ($rel -eq "nv2a/pgraph/s3tc.c" -or $rel -eq "nv2a/pgraph/s3tc.h") {
        return New-Entry "src/XGrid.Nv2a/S3tcDecoder.cs" "verified" "16 block vectors + texture oracle"
    }

    if ($rel -eq "nv2a/pgraph/psh_regs.h" -or $rel -eq "nv2a/pgraph/vsh_regs.h") {
        return New-Entry "src/XGrid.Nv2a/PshCombiner.cs" "ported" "register decode"
    }

    if ($rel -eq "nv2a/pgraph/util.h") {
        return New-Entry "src/XGrid.Nv2a/TextureFormats.cs" "ported" "helpers"
    }

    if ($rel -match "nv2a/pgraph/(rdi|profile|debug_renderdoc)\.c$") {
        return New-Entry "-" "n/a" "debug/profiling surface"
    }

    if ($rel -like "nv2a/pgraph/*") {
        return New-Entry "src/XGrid.Nv2a/Nv2aMmio.cs" "in-progress" "register/method pre-post table (XFP1-XFP4)"
    }

    if ($rel -match "nv2a/(stubs|user|debug)\.(c|h)$" -or $rel -match "nv2a/debug_gl\.h$" -or $rel -match "nv2a/trace\.h$") {
        return New-Entry "-" "n/a" "debug/stub surface"
    }

    if ($rel -like "nv2a/*") {
        return New-Entry "src/XGrid.Nv2a/Nv2aMmio.cs" "in-progress" "1B method/IRQ counters"
    }

    if ($rel -match "mcpx/apu/(debug\.c|monitor\.c|trace\.h|apu_debug\.h)$") {
        return New-Entry "-" "n/a" "debug/trace surface"
    }

    if ($rel -eq "mcpx/apu/apu_regs.h" -or $rel -eq "mcpx/apu/apu_int.h") {
        return New-Entry "src/XGrid.Audio/Vp/ApuVpFrame.cs" "ported" "constants, TM8"
    }

    if ($rel -eq "mcpx/apu/fpconv.h") {
        return New-Entry "src/XGrid.Audio/Vp/ApuVpFrame.cs" "verified" "TM8 PCM"
    }

    if ($rel -like "mcpx/apu/vp/*") {
        return New-Entry "src/XGrid.Audio/McpxApuDevice.Vp.cs" "verified" "TM8 PCM/DFT policy"
    }

    if ($rel -eq "mcpx/apu/dsp/dsp_jit.c" -or $rel -eq "mcpx/apu/dsp/trace.h") {
        return New-Entry "-" "n/a" "optional JIT / trace surface"
    }

    if ($rel -like "mcpx/apu/dsp/*") {
        return New-Entry "src/XGrid.Audio/Dsp/Dsp56300Core.cs" "verified" "929-vector oracle, P1.2"
    }

    if ($rel -eq "mcpx/apu/apu.c" -or $rel -eq "mcpx/apu/apu.h") {
        return New-Entry "src/XGrid.Audio/McpxApuDevice.cs" "in-progress" "register + frame vectors"
    }

    if ($rel -eq "mcpx/aci.c") {
        return New-Entry "src/XGrid.Bus/Aci/McpxAciDevice.cs" "in-progress" "AC'97 codec vectors (XFP6)"
    }

    if ($rel -eq "mcpx/nvnet/nvnet.c" -or $rel -eq "mcpx/nvnet/nvnet_regs.h") {
        return New-Entry "src/XGrid.Bus/Net/McpxNvNetDevice.cs" "in-progress" "DHCP/ARP frame vectors (XFP8)"
    }

    if ($rel -eq "mcpx/nvnet/trace.h") {
        return New-Entry "-" "n/a" "trace surface"
    }

    $top = @{
        "xbox.c" = @("src/XGrid.Host/XboxMachine.cs", "in-progress", "1B boot + ktest")
        "xbox.h" = @("src/XGrid.Host/XboxMachine.cs", "in-progress", "type/shape only")
        "xbox_pci.c" = @("src/XGrid.Bus/Pci/PciBus.cs", "in-progress", "PCI config reads vs reference")
        "xbox_pci.h" = @("src/XGrid.Bus/Pci/PciBus.cs", "in-progress", "type/shape only")
        "acpi_xbox.c" = @("new", "not-started", "ACPI PM1 / SMBus wake path")
        "acpi_xbox.h" = @("new", "not-started", "type/shape only")
        "amd_smbus.c" = @("src/XGrid.Bus/Smbus/Amd756Smbus.cs", "in-progress", "bus transaction vectors")
        "amd_smbus.h" = @("src/XGrid.Bus/Smbus/Amd756Smbus.cs", "in-progress", "type/shape only")
        "smbus.h" = @("src/XGrid.Bus/Smbus/SmbusDevice.cs", "in-progress", "type/shape only")
        "smbus_xbox_smc.c" = @("src/XGrid.Bus/Smbus/SmcDevice.cs", "in-progress", "SMC command/reply vectors")
        "smbus_adm1032.c" = @("new", "not-started", "temperature device")
        "smbus_cx25871.c" = @("src/XGrid.Bus/Smbus/ConexantCx25871.cs", "in-progress", "video-encoder state")
        "smbus_fs454.c" = @("new", "not-started", "fan controller")
        "smbus_storage.c" = @("new", "not-started", "SMBus EEPROM/IPMI path")
        "smbus_xcalibur.c" = @("new", "not-started", "video encoder")
        "eeprom_generation.c" = @("src/XGrid.Bus/Smbus/Eeprom24c02.cs", "in-progress", "EEPROM image vectors")
        "eeprom_generation.h" = @("src/XGrid.Bus/Smbus/Eeprom24c02.cs", "in-progress", "type/shape only")
        "lpc47m157.c" = @("new", "not-started", "Super-I/O")
        "xblc.c" = @("new", "not-started", "boot-logic controller")
        "xid.c" = @("src/XGrid.Bus/Usb/XidGamepad.cs", "in-progress", "XID descriptor/state")
        "xid.h" = @("src/XGrid.Bus/Usb/XidGamepad.cs", "in-progress", "type/shape only")
        "xid-gamepad.c" = @("src/XGrid.Bus/Usb/XidGamepad.cs", "in-progress", "pad report vectors")
    }

    if ($top.ContainsKey($rel)) {
        $entry = $top[$rel]
        return New-Entry $entry[0] $entry[1] $entry[2]
    }

    return New-Entry "new" "not-started" "unclassified (add a rule)"
}

function Get-ReferenceFiles {
    $base = (Resolve-Path $refDir).Path
    return @(Get-ChildItem $refDir -Recurse -File |
        ForEach-Object { $_.FullName.Substring($base.Length + 1).Replace('\', '/') } |
        Sort-Object)
}

function Format-FileList {
    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add($beginMarker)
    $lines.Add("")
    $lines.Add("| Reference file | Target C# | Status | Differential class |")
    $lines.Add("|---|---|---|---|")
    foreach ($rel in Get-ReferenceFiles) {
        $entry = Get-Entry $rel
        $lines.Add("| ``$rel`` | ``$($entry.Target)`` | $($entry.Status) | $($entry.Class) |")
    }

    $lines.Add("")
    $lines.Add($endMarker)
    return ($lines -join "`n")
}

function Update-FileList {
    $text = Get-Content $manifestPath -Raw
    $generated = Format-FileList
    if ($text.Contains($beginMarker) -and $text.Contains($endMarker)) {
        $start = $text.IndexOf($beginMarker)
        $end = $text.IndexOf($endMarker) + $endMarker.Length
        $text = $text.Substring(0, $start) + $generated + $text.Substring($end)
    }
    else {
        $text = $text.TrimEnd() + "`n`n## 7. hw/xbox per-file coverage`n`n" +
            "Generated from ``References2/xemu-0.8.139/hw/xbox`` by " +
            "``scripts/port-manifest.ps1 -UpdateFileList``. The grouped ledger above is the " +
            "human summary; this table is the authoritative per-file coverage." + "`n`n" + $generated + "`n"
    }

    Set-Content -Path $manifestPath -Value $text -NoNewline
    Write-Host "updated $manifestPath ($((Get-ReferenceFiles).Count) reference files)"
}

function Get-AppendixEntries {
    $text = Get-Content $manifestPath -Raw
    $start = $text.IndexOf($beginMarker)
    $end = $text.IndexOf($endMarker)
    if ($start -lt 0 -or $end -lt 0) {
        return $null
    }

    $body = $text.Substring($start, $end - $start)
    $entries = @{}
    foreach ($line in ($body -split "`n")) {
        if ($line -match '^\| `([^`]+)` \| `([^`]+)` \| ([a-z/-]+) \| (.*) \|$') {
            $entries[$Matches[1]] = [pscustomobject]@{
                Target = $Matches[2]
                Status = $Matches[3]
                Class = $Matches[4]
            }
        }
    }

    return $entries
}

function Test-TargetExists([string]$target) {
    if ([string]::IsNullOrWhiteSpace($target) -or $target -eq "-" -or $target -eq "new") {
        return $true
    }

    foreach ($part in ($target -split ",")) {
        $candidate = $part.Trim()
        if ($candidate -eq "new") {
            continue
        }

        if (-not (Test-Path (Join-Path $root $candidate))) {
            return $false
        }
    }

    return $true
}

if ($UpdateFileList) {
    Update-FileList
    if (-not $Check) {
        exit 0
    }
}

$failures = [System.Collections.Generic.List[string]]::new()
$entries = Get-AppendixEntries
if ($null -eq $entries) {
    $failures.Add("per-file appendix missing; run: pwsh -File scripts/port-manifest.ps1 -UpdateFileList")
}
else {
    $reference = Get-ReferenceFiles
    foreach ($rel in $reference) {
        if (-not $entries.ContainsKey($rel)) {
            $failures.Add("reference file has no row: hw/xbox/$rel")
        }
    }

    foreach ($key in $entries.Keys) {
        if ($reference -notcontains $key) {
            $failures.Add("stale row (file no longer in the reference tree): hw/xbox/$key")
        }
    }
}

# Ported/verified rows must name an existing target.
if ($null -ne $entries) {
    foreach ($key in $entries.Keys) {
        $entry = $entries[$key]
        if ($entry.Status -in @("ported", "verified") -and -not (Test-TargetExists $entry.Target)) {
            $failures.Add("$key is $($entry.Status) but its target does not exist: $($entry.Target)")
        }
    }
}

# Orphan port headers: a `Ported from`/`Derived from` path must be in the ledger.
$manifestText = Get-Content $manifestPath -Raw
$sourceFiles = Get-ChildItem (Join-Path $root "src") -Recurse -File -Filter *.cs
foreach ($file in $sourceFiles) {
    foreach ($line in (Get-Content $file.FullName)) {
        if ($line -match '(Ported from|Derived from)\s+(xemu|QEMU)[^`]*?((hw|target|tcg|accel|softmmu|system|block|net|migration|ui|audio|input)/[A-Za-z0-9_./+-]+)') {
            $refPath = $Matches[3].TrimEnd('.', ',', ')', ';')
            $leaf = Split-Path $refPath -Leaf
            if (-not $manifestText.Contains($leaf) -and -not $manifestText.Contains($refPath)) {
                $failures.Add("orphan port header in $($file.FullName.Substring($root.Length + 1)): $refPath")
            }
        }
    }
}

# Notices: every ported/verified reference file is named by basename.
$noticesText = Get-Content $noticesPath -Raw
if ($null -ne $entries) {
    foreach ($key in $entries.Keys) {
        $entry = $entries[$key]
        if ($entry.Status -in @("ported", "verified")) {
            $leaf = Split-Path $key -Leaf
            if (-not $noticesText.Contains($leaf)) {
                $failures.Add("notices do not name $key (expected '$leaf' in THIRD_PARTY_NOTICES.md)")
            }
        }
    }
}

# Coverage summary.
if ($null -ne $entries) {
    $order = @("verified", "ported", "in-progress", "not-started", "out-of-scope", "n/a")
    $counts = @{}
    foreach ($status in $order) { $counts[$status] = 0 }
    foreach ($entry in $entries.Values) {
        if ($counts.ContainsKey($entry.Status)) { $counts[$entry.Status]++ }
        else { $counts[$entry.Status] = 1 }
    }

    $total = $entries.Count
    $inScope = $total - $counts["n/a"] - $counts["out-of-scope"]
    $verified = $counts["verified"]
    $share = if ($inScope -gt 0) { 100.0 * $verified / $inScope } else { 0 }
    Write-Host ("hw/xbox files: total={0} in-scope={1} verified={2} ({3:F1}%)" -f $total, $inScope, $verified, $share)
    foreach ($status in $order) {
        Write-Host ("  {0,-12} {1}" -f $status, $counts[$status])
    }
}

if ($failures.Count -gt 0) {
    Write-Host ""
    Write-Host "PORT MANIFEST: FAIL ($($failures.Count))"
    foreach ($failure in $failures) {
        Write-Host "  $failure"
    }

    exit 1
}

Write-Host "PORT MANIFEST: PASS"
exit 0
