#!/usr/bin/env python3
"""run_xemu_ktest_smoke.py - xemu leg of the §123 ktest smoke.

Boots the parked subset suite (see patch_suite_xbe.py --park; the suite spins
at VA 0x4E03A after close_output_file instead of returning, so the kernel
never relaunches the XBE and the FATX log is never truncated) and quits via
the QEMU monitor once EIP==PARK_EIP for --settle consecutive samples.

Profile layout (all private, generated by scripts/ktest-smoke.ps1):
  <dir>/xemu.toml      [sys.files] bootrom/flashrom/eeprom/hdd/dvd paths
  <dir>/ktest-hdd.qcow2  private HDD copy (xemu commits guest writes into it)

Usage:
  python run_xemu_ktest_smoke.py --dir <profile> --xemu-exe <xemu.exe>
      [--tag s] [--port 4446] [--interval 1.0] [--settle 3] [--timeout 420]

Outputs (under <dir>/): <tag>_console.txt.
Exit 0 = parked (log complete, safe to read back), 1 = timeout/failure.
"""

import argparse
import os
import re
import socket
import subprocess
import sys
import time

EIP_RE = re.compile(r"EIP=([0-9a-fA-F]+)")
PARK_EIP = 0x4E03A


class Monitor:
    def __init__(self, port, timeout=15.0):
        self.sock = socket.create_connection(("127.0.0.1", port), timeout=timeout)
        self.sock.settimeout(timeout)
        self.buf = b""
        self._read_until_prompt()

    def _read_until_prompt(self):
        while True:
            chunk = self.sock.recv(4096)
            if not chunk:
                raise ConnectionError("monitor closed")
            self.buf += chunk
            if self.buf.endswith(b"(qemu) "):
                text = self.buf[: -len(b"(qemu) ")]
                self.buf = b""
                return text

    def cmd(self, command):
        self.sock.sendall(command.encode("ascii") + b"\n")
        return self._read_until_prompt().decode("latin-1", "replace")


def eip_from_regs(text):
    m = EIP_RE.search(text)
    return int(m.group(1), 16) if m else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    ap.add_argument("--xemu-exe", required=True)
    ap.add_argument("--bios", default=None,
                    help="flash ROM image (default: <dir>/Complex_4627.bin)")
    ap.add_argument("--tag", default="s")
    ap.add_argument("--port", type=int, default=4446)
    ap.add_argument("--interval", type=float, default=1.0)
    ap.add_argument("--settle", type=int, default=3)
    ap.add_argument("--timeout", type=float, default=420.0)
    args = ap.parse_args()

    profile = os.path.abspath(args.dir)
    toml = os.path.join(profile, "xemu.toml")
    assert os.path.isfile(toml), "missing " + toml
    bios = os.path.abspath(args.bios or os.path.join(profile, "Complex_4627.bin"))
    assert os.path.isfile(bios), "missing " + bios
    console_path = os.path.join(profile, f"{args.tag}_console.txt")
    console = open(console_path, "wb")
    proc = subprocess.Popen(
        # NOTE: -bios is passed explicitly because xemu 0.8.136 does not
        # bridge xemu.toml flashrom_path into QEMU -bios (launch params show
        # no -bios and xbox.c reads ms->firmware; "Failed to load BIOS
        # '(null)' otherwise). §123 diagnosis.
        [args.xemu_exe, "-bios", bios, "-monitor",
         f"tcp:127.0.0.1:{args.port},server,nowait",
         "-config_path", toml],
        cwd=profile,
        stdout=console,
        stderr=subprocess.STDOUT,
    )

    mon = None
    deadline = time.time() + 60
    while time.time() < deadline:
        if proc.poll() is not None:
            print("xemu exited early, see", console_path)
            return 1
        try:
            mon = Monitor(args.port, timeout=5.0)
            break
        except OSError:
            time.sleep(1.0)
    if mon is None:
        proc.kill()
        print("monitor never came up")
        return 1

    print("xemu pid", proc.pid)
    # xemu starts the VM in "paused (prelaunch)" when driven headlessly via
    # -monitor; nothing executes until 'cont'. Without this the EIP sits at
    # the reset vector 0xFFF0 forever (§123 diagnosis).
    try:
        mon.cmd("cont")
    except Exception as exc:  # noqa: BLE001
        print("cont failed:", exc)
        return 1
    start = time.time()
    saw_suite = 0
    park_hits = 0
    samples = 0
    reason = "timeout"
    try:
        while time.time() - start < args.timeout:
            regs = mon.cmd("info registers")
            samples += 1
            eip = eip_from_regs(regs)
            in_suite = eip is not None and 0x10000 <= eip < 0x5B000
            if in_suite:
                saw_suite += 1
            if eip == PARK_EIP:
                park_hits += 1
            else:
                park_hits = 0
            elapsed = time.time() - start
            print("t=%6.1fs EIP=%s suite=%d park=%d" % (
                elapsed, ("%08x" % eip) if eip is not None else "?",
                saw_suite, park_hits))
            if park_hits >= args.settle:
                reason = "parked"
                break
            time.sleep(args.interval)
    except Exception as exc:  # noqa: BLE001 - monitor may drop if xemu dies
        print("monitor lost:", exc)
        reason = "monitor-lost"
    finally:
        try:
            mon.cmd("quit")
        except Exception:
            proc.kill()
        console.close()
        try:
            proc.wait(timeout=15)
        except Exception:
            proc.kill()

    print("done; reason=%s samples=%d saw_suite=%d" % (reason, samples, saw_suite))
    return 0 if reason == "parked" else 1


if __name__ == "__main__":
    sys.exit(main())
