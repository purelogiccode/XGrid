    private static void WritePatternImage(string path, int sectors)
    {
        byte[] image = new byte[sectors * 512];
        for (int lba = 0; lba < sectors; lba++)
        {
            for (int i = 0; i < 512; i++)
            {
                uint linear = (uint)((lba * 512) + i);
                image[(lba * 512) + i] = (byte)(((linear * 0x21u) ^ 0x5Au) & 0xFFu);
            }
        }

        File.WriteAllBytes(path, image);
    }

    private static void DeleteTempFile(string path)
    {
        if (!File.Exists(path))
        {
            return;
        }

        try
        {
            File.Delete(path);
        }
        catch (IOException)
        {
            // A failed assertion may leave the overlay handle open; the temp
            // file is harmless and will be reclaimed by the OS temp cleaner.
        }
    }

