    [Fact]
    public void Nv2aQuad_PassesWithTexturedFlipAndNonZeroFrame()
    {
        using var runner = new TestRomRunner(new XboxMachine(), "nv2a_quad");
        runner.LoadImage(Nv2aQuadRom, 0x1000, 0x1000, 0x80000);

        ulong executed = runner.Run(2_000_000);

        Assert.True(runner.Machine.Cpu.Context.Halted);
        Assert.True(runner.Passed);
        Assert.Equal(0u, runner.Machine.Cpu.Context.Eax);
        Assert.True(executed < 2_000_000);
        Assert.True(runner.Machine.Nv2A.DrawsExecuted >= 1);
        Assert.True(runner.Machine.Nv2A.TexturedPixels > 0);
        Assert.True(runner.Machine.Nv2A.FramesPresented >= 1);
        Assert.True(
            runner.Machine.Nv2A.TryCopyPresentedFrame(out uint width, out uint height, out byte[] bgra));
        Assert.Equal(64u, width);
        Assert.Equal(64u, height);

        uint nonzero = 0;
        for (int i = 0; i + 4 <= bgra.Length; i += 4)
        {
            if (bgra[i] != 0 || bgra[i + 1] != 0 || bgra[i + 2] != 0 || bgra[i + 3] != 0)
            {
                nonzero++;
            }
        }

        Assert.True(nonzero > 0);

        runner.Console.Flush();
        Assert.Contains(
            runner.Console.Lines,
            line => string.Equals(line, "nv2a-quad: surface matches", StringComparison.Ordinal));
    }

    [Fact]
    public void PassConvention_HaltedWithEaxZeroIsPass()
    {
        // mov eax, 0; hlt
        using var runner = new TestRomRunner(new XboxMachine(), "pass");
        runner.LoadImage(new byte[] { 0xB8, 0x00, 0x00, 0x00, 0x00, 0xF4 }, 0x1000, 0x1000, 0x80000);

        runner.Run(100);

        Assert.True(runner.Passed);
    }

    [Fact]
    public void FailConvention_NonZeroEaxIsFail()
    {
        // mov eax, 5; hlt
        using var runner = new TestRomRunner(new XboxMachine(), "fail");
        runner.LoadImage(new byte[] { 0xB8, 0x05, 0x00, 0x00, 0x00, 0xF4 }, 0x1000, 0x1000, 0x80000);

        runner.Run(100);

        Assert.False(runner.Passed);
        Assert.Equal(5u, runner.Machine.Cpu.Context.Eax);
    }

    [Fact]
    public void Console_OutE9CollectsLinesUntilHalt()
    {
        // mov dx, 0xE9; out 'h', 'i', 0x0A; xor eax, eax; hlt
        byte[] code =
        {
            0x66, 0xBA, 0xE9, 0x00,
            0xB0, 0x68, 0xEE,
            0xB0, 0x69, 0xEE,
            0xB0, 0x0A, 0xEE,
            0x31, 0xC0, 0xF4,
        };
        using var runner = new TestRomRunner(new XboxMachine(), "console");
        runner.LoadImage(code, 0x1000, 0x1000, 0x80000);

        runner.Run(100);

        Assert.True(runner.Passed);
        Assert.Single(runner.Console.Lines);
        Assert.Equal("hi", runner.Console.Lines[0]);
        Assert.Equal(3, runner.Console.ByteCount);
    }
